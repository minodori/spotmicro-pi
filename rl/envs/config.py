# 속도 추종 보상의 폭. exp(-오차^2 / SIGMA).
#
# 이 값은 **명령 범위에 맞춰야 한다.** 흔히 쓰는 0.25 는 1 m/s 이상으로 달리는
# 대형 4족 기준이며, 최대 0.3 m/s 인 이 로봇에서는 오차 제곱이 0.09 를 넘지 않아
# "가만히 서 있어도 최대 보상의 85%" 가 되어버린다. 실제로 2천만 스텝 학습이
# 정지 자세로 수렴했고, 이 값을 고쳐 300만 스텝만에 전진이 성립했다.
#
#   명령 0.2 에서  sigma 0.25  -> 정지 1.278 / 완벽 1.500  (차이 0.22)
#                  sigma 0.025 -> 정지 0.303 / 완벽 1.500  (차이 1.20)
