# ---------------------------------------------------------------------------
# 관측
# ---------------------------------------------------------------------------
# A안 — 관절 피드백 포함. 실물에는 없는 정보다
#   동체각속도 3 + 투영중력 3 + 속도명령 3 + 관절각 12 + 관절각속도 12 + 이전행동 12
# B안 — 관절 피드백 제외. 그 자리에 행동 이력
#   동체각속도 3 + 투영중력 3 + 속도명령 3 + 이전행동 12 x HIST_FRAMES
#
# 동체 선속도는 두 안 모두 제외한다. 상태 추정기도 깊이 카메라도 없어 실물에서
# 얻을 수 없고, 학습이 그것에 의존하면 이식 자체가 불가능해진다.
# (보상과 종료 조건에는 쓴다 — 학습 중에만 쓰는 특권 정보다.)
HIST_FRAMES = 5

SCALE_ANG_VEL = 0.25
SCALE_JOINT_VEL = 0.05


def obs_dim(mode: str) -> int:
    base = 3 + 3 + 3
    return base + (12 + 12 + 12) if mode == "A" else base + 12 * HIST_FRAMES


